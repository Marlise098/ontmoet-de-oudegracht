<div class="help">
    <section class="panel">
        <h2>Hoe werkt de app voor bezoekers?</h2>
        <p>Bezoekers kijken naar de film uit 1929. Naast de film staat een kaart waarop een bootje meevaart. Langs de gracht liggen <strong>plekken</strong> (genummerde punten). Zodra de film bij een plek komt, zien bezoekers het verhaal en de oude foto's van die plek. Ze kunnen ook zelf op een nummer tikken om er meteen naartoe te gaan.</p>
    </section>

    <section class="panel">
        <h2>Een tekst of foto aanpassen</h2>
        <ol>
            <li>Ga naar <a href="?page=locations">Plekken en foto's</a> en kies de plek.</li>
            <li>Pas de titel of tekst aan. Een lege regel begint een nieuwe alinea.</li>
            <li>Klik onderaan op <strong>Wijzigingen opslaan</strong>. De app op het digibord toont de wijziging bij de volgende keer laden (uiterlijk nadat de film in de wachtstand een keer is afgespeeld).</li>
            <li>Foto's beheer je onderaan dezelfde pagina: toevoegen, volgorde wijzigen met ↑ ↓, bewerken of verwijderen.</li>
        </ol>
    </section>

    <section class="panel">
        <h2>Een nieuwe plek toevoegen</h2>
        <ol>
            <li>Klik op <strong>+ Nieuwe plek</strong>.</li>
            <li>Vul een nummer (bijv. <em>4</em> of <em>3a</em>) en een titel in.</li>
            <li>Speel de film af in stap 3 en druk op <strong>Gebruik dit moment</strong> wanneer de boot bij de plek is.</li>
            <li>Tik in stap 4 op de kaart waar de plek ligt.</li>
            <li>Sla op en voeg daarna foto's toe.</li>
        </ol>
        <p>Werk je nog aan een plek? Zet dan <em>Toon deze plek aan bezoekers</em> uit. In de lijst met plekken kun je dit met één klik aan- en uitzetten.</p>
    </section>

    <section class="panel">
        <h2>Foto's uit de beeldbank gebruiken</h2>
        <ol>
            <li>Zoek de foto op <a href="https://hetutrechtsarchief.nl/beeldmateriaal" target="_blank" rel="noopener">hetutrechtsarchief.nl</a>.</li>
            <li>Download de foto en upload hem via <strong>Foto uploaden</strong>, of plak een directe link naar de afbeelding.</li>
            <li>Vul altijd de <strong>maker</strong>, het <strong>catalogusnummer</strong> en de <strong>licentie</strong> in. Die worden bij de foto getoond.</li>
            <li>Plak de link naar de beeldbankpagina in <em>Link naar de beeldbank</em>, zodat collega's de bron terugvinden.</li>
        </ol>
        <p class="hint">Geüploade foto's worden automatisch verkleind tot maximaal 1600 pixels, zodat ze snel laden.</p>
    </section>

    <section class="panel">
        <h2>De route van de boot bijstellen</h2>
        <p>Loopt het bootje op de kaart voor of achter op de film? Ga naar <a href="?page=route">Route van de boot</a>. Spoel de film naar een herkenbaar moment (bijvoorbeeld onder een brug), druk op <strong>Nieuw routepunt</strong> en tik op de kaart waar de boot op dat moment is. Je kunt bestaande punten ook verplaatsen met <strong>Kies op kaart</strong>.</p>
    </section>

    <section class="panel">
        <h2>Welkomsttekst en colofon</h2>
        <p>De teksten van het welkomstscherm, het colofon en de titel pas je aan bij <a href="?page=settings">Teksten en instellingen</a>. Daar stel je ook in na hoeveel seconden zonder aanraking het digibord terugspringt naar de wachtstand. In de wachtstand speelt de film zonder geluid en vaart de boot mee, zodat het scherm ook op afstand opvalt.</p>
    </section>

    <section class="panel">
        <h2>Veiligheid</h2>
        <ul>
            <li>Deel je wachtwoord met niemand. Een beheerder kan voor nieuwe collega's een account maken.</li>
            <li>Na 5 verkeerde wachtwoorden wordt inloggen 10 minuten geblokkeerd.</li>
            <li>Na 2 uur zonder activiteit word je automatisch uitgelogd.</li>
            <li>Bij <a href="?page=dashboard">Overzicht</a> zie je wie wat heeft gewijzigd.</li>
        </ul>
    </section>
